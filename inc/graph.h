/// @file graph.h
/// @brief Взвешенный неориентированный граф и структура ребра.

#ifndef GRAPH_H
#define GRAPH_H

#include <string>
#include <vector>

/// @brief Ребро взвешенного неориентированного графа.
struct Edge {
    int from;      ///< Начальная вершина ребра.
    int to;        ///< Конечная вершина ребра.
    double weight; ///< Вес ребра.
};

/// @brief Взвешенный неориентированный граф, представленный списками смежности.
///
/// Граф загружается из текстового файла, содержащего матрицу смежности весов.
class Graph {
public:
    /// @brief Загружает граф из файла с матрицей смежности весов.
    ///
    /// Формат файла: первая строка содержит количество вершин N,
    /// далее N строк по N чисел — матрица весов. Нулевое значение означает
    /// отсутствие ребра, положительные значения — вес ребра. Граф
    /// предполагается неориентированным, поэтому матрица должна быть
    /// симметричной (учитывается только верхний треугольник).
    ///
    /// @param filename Имя входного файла.
    /// @return true, если граф успешно загружен.
    bool loadFromMatrixFile(const std::string& filename);

    /// @brief Возвращает количество вершин графа.
    int vertexCount() const;

    /// @brief Возвращает список смежности заданной вершины.
    ///
    /// Для каждого ребра списка поле from равно @p vertex, поле to — сосед.
    ///
    /// @param vertex Номер вершины.
    /// @return Список рёбер, инцидентных вершине.
    const std::vector<Edge>& adjacency(int vertex) const;

private:
    int vertex_count_ = 0;                          ///< Количество вершин.
    std::vector<std::vector<Edge>> adjacency_list_; ///< Списки смежности.
};

#endif // GRAPH_H
